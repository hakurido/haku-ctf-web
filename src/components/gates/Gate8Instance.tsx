"use client";

import React from "react";
import type { Gate8Challenge } from "@/lib/api";
import { TextField } from "../ui/Field";
import { useAppState } from "../state/AppStateProvider";

export interface Gate8InstanceProps {
  data: Gate8Challenge;
  readOnly: boolean;
}

export function Gate8Instance({ data, readOnly }: Gate8InstanceProps) {
  const { state, setField } = useAppState();

  return (
    <div className="space-y-5">
      <div>
        <div className="flex items-center justify-between mb-1.5">
          <h3 className="text-ui font-semibold text-fg">
            Non-Linear Filter Generator (LFSR-32)
          </h3>
          <span className="text-caption font-mono text-fg-muted">
            Taps: [32, 22, 2, 1, 0] · ANF Degree-2
          </span>
        </div>
        <p className="text-caption text-fg-muted mb-2 font-mono">
          Filter: {data.filterFormula || "z_t = s_t ^ (s_{t-3} & s_{t-7}) ^ (s_{t-12} & s_{t-20})"}
        </p>
        <p className="text-caption text-fg-secondary mb-3">
          Non-linear terms destroy linear recurrence, defeating Berlekamp-Massey. Solve initial 32-bit state via Algebraic SMT Attack (Z3) and extrapolate next 32 bits.
        </p>

        <div className="p-3 rounded-md border border-line bg-inset font-mono text-code break-all select-all text-accent tracking-wider">
          <span className="text-caption text-fg-muted block mb-1">Observed Keystream (64 bits):</span>
          {data.observedBits}
        </div>
      </div>

      <div>
        <TextField
          label="Predicted keystream (next 32 bits)"
          description="32-character binary string ('0' and '1') for the next 32 bits generated by the NLFG."
          mono
          value={state.gate8.inputs}
          onChange={(e) => setField("gate8.inputs", e.target.value)}
          disabled={readOnly}
          placeholder="e.g. 10101100101101011010011010110100"
        />
      </div>
    </div>
  );
}
